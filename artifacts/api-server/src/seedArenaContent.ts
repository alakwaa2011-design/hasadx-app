// Image-URL backfill (Task #603 — fixes broken Wikimedia thumbnail links that
// return HTTP 400 due to Wikimedia's User-Agent / hotlink policy). Updates the
// existing image-questions in "أمثال شعبية" by exact question-text match.
// Idempotent: re-running with the same target URL is a no-op.
// ─────────────────────────────────────────────────────────────────────────────
