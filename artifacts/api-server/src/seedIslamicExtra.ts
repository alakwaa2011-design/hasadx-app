export async function seedIslamicExtraIfNeeded(): Promise<void> {
  try {
    let totalInserted = 0;
    let categoriesProcessed = 0;

    for (const sectionSpec of EXTRA_SECTIONS) {
      let section = (
        await db
          .select()
          .from(islamicSectionsTable)
          .where(eq(islamicSectionsTable.name, sectionSpec.name))
          .limit(1)
      )[0];
      if (!section) {
        [section] = await db
          .insert(islamicSectionsTable)
          .values({
            name: sectionSpec.name,
            description: sectionSpec.description,
            isVisible: true,
            order: sectionSpec.order,
          })
          .returning();
      }

      for (const cat of sectionSpec.categories) {
        let catRow = (
          await db
            .select()
            .from(islamicCategoriesTable)
            .where(
              and(
                eq(islamicCategoriesTable.sectionId, section.id),
                eq(islamicCategoriesTable.name, cat.name),
              ),
            )
            .limit(1)
        )[0];

        if (!catRow) {
          [catRow] = await db
            .insert(islamicCategoriesTable)
            .values({
              sectionId: section.id,
              name: cat.name,
              description: cat.description,
              level: cat.level,
              order: cat.order,
              isVisible: true,
            })
            .returning();
        }

        // Idempotent per question: only insert questions whose text isn't
        // already present in this category. This lets us safely append
        // more entries to the array over time.
        const existing = await db
          .select({ qt: islamicQuestionsTable.questionText })
          .from(islamicQuestionsTable)
          .where(eq(islamicQuestionsTable.categoryId, catRow.id));
        const existingSet = new Set(
          existing.map((r) => (r.qt || "").trim().toLowerCase()),
        );

        const toInsert = cat.questions.filter(
          (q) => !existingSet.has(q.q.trim().toLowerCase()),
        );

        if (toInsert.length > 0) {
          await db.insert(islamicQuestionsTable).values(
            toInsert.map((q) => ({
              categoryId: catRow.id,
              questionText: q.q,
              optionA: q.a,
              optionB: q.b,
              optionC: q.c,
              optionD: q.d,
              correctAnswer: q.correct,
              difficulty: q.difficulty,
            })),
          );
          totalInserted += toInsert.length;
        }
        categoriesProcessed++;
      }
    }

    if (totalInserted > 0) {
      logger.info(
        { totalInserted, categoriesProcessed },
        "[seedIslamicExtra] inserted new questions",
      );
    } else {
      logger.info("[seedIslamicExtra] no new questions to insert");
    }
  } catch (err) {
    logger.error({ err }, "[seedIslamicExtra] failed");
  }
}
