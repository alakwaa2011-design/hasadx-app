export function collaborationText(value: string, lang: Language): string {
  if (lang === "ar") return value;
  const exact = english[value];
  if (exact !== undefined) return exact;

  const reviewTitle = value.match(/^مراجعة المشاركات \((\d+)\)$/);
  if (reviewTitle) return `Review posts (${reviewTitle[1]})`;
  const participantsTitle = value.match(/^المشاركون \((\d+)\)$/);
  if (participantsTitle) return `Participants (${participantsTitle[1]})`;
  const reviewCount = value.match(/^مراجعة المشاركات \((\d+)\)$/);
  if (reviewCount) return `Review posts (${reviewCount[1]})`;
  const destinationBody = value.match(/^القسم «(.*)» يحتوي (\d+) مشاركة\.\s*لن تُحذف المشاركات\. اختر القسم الذي ستُنقل إليه قبل تأكيد حذف القسم\.$/);
  if (destinationBody) return `Section “${destinationBody[1]}” contains ${destinationBody[2]} post(s). The posts will not be deleted. Choose a section to move them to before confirming deletion.`;
  const memberPostCount = value.match(/^(\d+) مشاركة( - محظور)?$/);
  if (memberPostCount) return `${memberPostCount[1]} post(s)${memberPostCount[2] ? " · Blocked" : ""}`;
  const completedReview = value.match(/^تم (اعتماد|رفض) (\d+) مشاركة\.$/);
  if (completedReview) return `${completedReview[1] === "اعتماد" ? "Approved" : "Rejected"} ${completedReview[2]} post(s).`;
  const textTooLong = value.match(/^النص أطول من (\d+) حرف\.$/);
  if (textTooLong) return `Text exceeds ${textTooLong[1]} characters.`;
  const postLimit = value.match(/^يمكنك إضافة (\d+) بطاقات إلى هذه اللوحة\.$/);
  if (postLimit) return `You can add ${postLimit[1]} posts to this board.`;
  return value;
}

export function useCollabText() {
  const { lang } = useI18n();
  return useCallback((value: string) => collaborationText(value, lang), [lang]);
}
