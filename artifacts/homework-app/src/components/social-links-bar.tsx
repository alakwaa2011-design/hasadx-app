interface Props {
  links: SocialLink[];
  /** "icon" = أيقونة مربّعة فقط (للهيدر). "full" = أيقونة + اسم @handle (للفوتر). */
  variant?: "icon" | "full";
  className?: string;
}

export function SocialLinksBar({ links, variant = "icon", className = "" }: Props) {
  const visible = links
    .filter(l => l.enabled && l.url.trim())
    .sort((a, b) => a.order - b.order);

  if (visible.length === 0) return null;

  return (
    <div className={`flex items-center gap-2 flex-wrap ${className}`}>
      {visible.map(link => {
        const meta = PLATFORM_META[link.id] ?? {
          label: link.id,
          color: "#888",
          icon: <span className="text-[9px] font-black">{link.id.slice(0,2).toUpperCase()}</span>,
        };

        const iconBg = meta.gradient
          ? { background: meta.gradient }
          : { background: meta.color ?? "#888" };

        const isDark = meta.color === "#FFFC00" || meta.color === "#FFF" || meta.color === "#ffffff";

        return (
          <a
            key={link.id}
            href={link.url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={meta.label}
            title={meta.label}
            className={`group flex items-center gap-1.5 transition-all duration-200 hover:scale-110 ${variant === "full" ? "text-xs text-muted-foreground hover:text-foreground" : ""}`}
          >
            <span
              className="flex items-center justify-center w-7 h-7 rounded-lg shrink-0"
              style={{ ...iconBg, color: isDark ? "#000" : "#fff" }}
            >
              {meta.icon}
            </span>
            {variant === "full" && (
              <span className="hidden sm:inline font-medium">
                {link.url.replace(/^https?:\/\/(www\.)?/, "").split("/")[0]}
              </span>
            )}
          </a>
        );
      })}
    </div>
  );
}
