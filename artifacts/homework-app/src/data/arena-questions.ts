import { getStaticCoverImage } from "./arena-cover-images";

export type ArenaDifficulty = 200 | 400 | 600 | 800;

export type ArenaQuestionType =
  | "text"
  | "image"
  | "video"
  | "audio"
  | "memory"
  | "sin-jeem"
  | "categorize"
  | "logo"
  | "secret";

/** Memory-match pair: each side can be a text label or an image URL. */
export interface MemoryPair {
  a: { kind: "text" | "image"; value: string };
  b: { kind: "text" | "image"; value: string };
}
export interface MemoryPayload {
  pairs: MemoryPair[];
}

/** سين جيم — one letter, several prompts the team must answer with words starting with that letter. */
export interface SinJeemPrompt {
  prompt: string;
  answer: string;
}
export interface SinJeemPayload {
  letter: string;
  prompts: SinJeemPrompt[];
}

/** Categorize / جمعة — items must be sorted into named groups. */
export interface CategorizeGroup {
  name: string;
  items: string[];
}
export interface CategorizePayload {
  groups: CategorizeGroup[];
}

/** Logo guess — uses imageUrl + answer; optional hint shown on demand. */
export interface LogoPayload {
  hint?: string;
}

/** اكتشف السر — two-team yes/no guessing game embedded in the arena tile. */
export interface SecretPayload {
  categoryId: number;
  maxQuestions?: number;
}

export type ArenaQuestionPayload =
  | MemoryPayload
  | SinJeemPayload
  | CategorizePayload
  | LogoPayload
  | SecretPayload
  | null
  | undefined;

export interface ArenaQuestion {
  q: string;
  a: string;
  hint?: string;
  type?: ArenaQuestionType;
  imageUrl?: string;
  videoUrl?: string;
  payload?: ArenaQuestionPayload;
}

export interface ArenaCover {
  emoji: string;
  color: string;
  gradient?: string;
  imageUrl?: string | null;
}

export interface ArenaSubCategory {
  id: string;
  name: string;
  questions: Record<ArenaDifficulty, ArenaQuestion[]>;
  cover?: ArenaCover;
}

export interface ArenaSection {
  id: string;
  name: string;
  emoji: string;
  cover?: ArenaCover;
  subCategories: ArenaSubCategory[];
}

