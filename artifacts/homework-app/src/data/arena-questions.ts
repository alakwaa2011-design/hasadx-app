export interface ArenaCustomQuestion {
  q: string;
  a: string;
  difficulty: ArenaDifficulty;
}

/**
 * Builds a virtual section that wraps the teacher's custom questions so they
 * can be picked alongside the default sections in the setup wizard. Empty
 * difficulty buckets are filled with the full custom pool so the card grid
 * always has a question to draw from for each 200/400/600 slot.
 */
// ─────────────────────────  Static cover image hydration  ────────────────────
//
// Each built-in section/sub-category gets a polished bundled cover image when
// one exists in `src/assets/arena-covers/<sectionId>__<subId>.png`. The image
// replaces the plain emoji + gradient that the cards render by default, while
// keeping the section's palette color/gradient as the title-bar background and
// fallback. Any section/sub without a matching asset silently falls back to
// the original emoji + gradient cover.
ARENA_SECTIONS.forEach((section, sectionIdx) => {
  const sectionPalette = ARENA_COVER_PALETTE[sectionIdx % ARENA_COVER_PALETTE.length];
  const sectionImage = getStaticCoverImage(section.id, section.id);
  if (!section.cover) {
    section.cover = {
      emoji: section.emoji,
      color: sectionPalette.color,
      gradient: sectionPalette.gradient,
      imageUrl: sectionImage ?? null,
    };
  }
  section.subCategories.forEach((sub) => {
    const subImage = getStaticCoverImage(section.id, sub.id);
    if (!subImage) return;
    sub.cover = {
      emoji: sub.cover?.emoji ?? section.emoji,
      color: sub.cover?.color ?? sectionPalette.color,
      gradient: sub.cover?.gradient ?? sectionPalette.gradient,
      imageUrl: subImage,
    };
  });
});

export function buildCustomSection(
  customs: ArenaCustomQuestion[],
): ArenaSection | null {
  if (customs.length === 0) return null;
  const byDiff: Record<ArenaDifficulty, ArenaQuestion[]> = { 200: [], 400: [], 600: [], 800: [] };
  for (const c of customs) byDiff[c.difficulty].push({ q: c.q, a: c.a });
  const allQs = customs.map(c => ({ q: c.q, a: c.a }));
  for (const d of [200, 400, 600, 800] as ArenaDifficulty[]) {
    if (byDiff[d].length === 0) byDiff[d] = allQs;
  }
  return {
    id: "custom",
    name: "أسئلتي المخصصة",
    emoji: "🎯",
    subCategories: [{ id: "custom-mine", name: "أسئلتي", questions: byDiff }],
  };
}
