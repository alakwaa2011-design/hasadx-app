/* Regenerates `lib/api-zod/src/generated/types-reexport.ts` after orval
   wipes the generated/ folder. Re-exports every generated type EXCEPT
   ones whose PascalCase filename collides with a Zod schema constant
   exported from `api.ts` (e.g. `CreatePresentationBody` exists as both
   a Zod schema in api.ts and a TS interface in types/, and TS won't
   let us re-export both under the same name from `index.ts`). */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..", "..");
const typesDir = resolve(repoRoot, "lib/api-zod/src/generated/types");
const apiPath = resolve(repoRoot, "lib/api-zod/src/generated/api.ts");
const outPath = resolve(repoRoot, "lib/api-zod/src/generated/types-reexport.ts");

const apiSrc = readFileSync(apiPath, "utf8");
const apiExports = new Set();
for (const m of apiSrc.matchAll(/^export const ([A-Za-z0-9_]+)/gm)) {
  apiExports.add(m[1]);
}

const files = readdirSync(typesDir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();

const lines = [
  "// AUTO-GENERATED by lib/api-spec/scripts/gen-types-reexport.mjs",
  "// Re-exports every generated type EXCEPT names that collide with",
  "// Zod schema constants exported from ./api.ts.",
  "",
];

let kept = 0;
for (const f of files) {
  const base = f.slice(0, -3);
  const pascal = base[0].toUpperCase() + base.slice(1);
  if (apiExports.has(pascal)) continue;
  lines.push(`export type * from "./types/${base}";`);
  kept += 1;
}

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`gen-types-reexport: wrote ${kept} re-exports`);
