async function seed() {
  const client = await pool.connect();
  try {
    // Check if path already exists
    const check = await client.query(
      `SELECT id FROM maraqui_paths WHERE title = 'مسابقة الصحابة الكرام' AND creator_type = 'organizer' LIMIT 1`
    );
    if (check.rows.length > 0) {
      console.log("✅ المسار موجود مسبقاً — ID:", check.rows[0].id);
      return;
    }

    const pin = String(Math.floor(100000 + Math.random() * 900000));
    const res = await client.query(
      `INSERT INTO maraqui_paths
         (title, description, pin, stages, creator_id, creator_type, is_public, is_approved)
       VALUES ($1, $2, $3, $4, 0, 'organizer', true, true)
       RETURNING id, pin`,
      [
        "مسابقة الصحابة الكرام",
        "٨ مراحل متنوعة للتعرف على الصحابة الكرام — من الخلفاء الراشدين إلى الصحابيات والفاتحين والعلماء",
        pin,
        JSON.stringify(stages),
      ]
    );
    console.log("✅ تم إنشاء مسار الصحابة — ID:", res.rows[0].id, "PIN:", res.rows[0].pin);
  } finally {
    client.release();
    await pool.end();
  }
}

seed().catch(e => { console.error("❌", e.message); process.exit(1); });
