// ─────────────────────────────────────────────────────────────────────────────
// MAIN — idempotent insert
// ─────────────────────────────────────────────────────────────────────────────
async function main(): Promise<void> {
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error("DATABASE_URL not set");
  }
  const client = new Client({ connectionString: url });
  await client.connect();
  let sectionsCreated = 0;
  let subsCreated = 0;
  let actsInserted = 0;
  try {
    let sIdx = 0;
    for (const section of SECTIONS) {
      // Find or create the section (parent_id IS NULL, is_public=true).
      const found = await client.query<{ id: number }>(
        `SELECT id FROM arena_categories
         WHERE name = $1 AND is_public = true AND parent_id IS NULL
         LIMIT 1`,
        [section.name],
      );
      let sectionId: number;
      if (found.rows.length > 0) {
        sectionId = found.rows[0]!.id;
      } else {
        const ins = await client.query<{ id: number }>(
          `INSERT INTO arena_categories
             (name, emoji, cover_image_url, cover_color, cover_gradient,
              parent_id, is_public, sort_order)
           VALUES ($1, $2, $3, $4, $5, NULL, true, $6)
           RETURNING id`,
          [
            section.name,
            section.emoji,
            section.coverImageUrl ?? null,
            section.coverColor,
            section.coverGradient ?? null,
            1000 + sIdx, // appears after the original sections (which use 0..N)
          ],
        );
        sectionId = ins.rows[0]!.id;
        sectionsCreated++;
      }

      let subIdx = 0;
      for (const sub of section.subs) {
        const subFound = await client.query<{ id: number }>(
          `SELECT id FROM arena_categories
           WHERE name = $1 AND parent_id = $2 AND is_public = true
           LIMIT 1`,
          [sub.name, sectionId],
        );
        let subId: number;
        if (subFound.rows.length > 0) {
          subId = subFound.rows[0]!.id;
        } else {
          const insSub = await client.query<{ id: number }>(
            `INSERT INTO arena_categories
               (name, emoji, cover_image_url, cover_color, cover_gradient,
                parent_id, is_public, sort_order)
             VALUES ($1, $2, $3, $4, $5, $6, true, $7)
             RETURNING id`,
            [
              sub.name,
              sub.emoji,
              sub.coverImageUrl ?? null,
              sub.coverColor,
              sub.coverGradient ?? null,
              sectionId,
              subIdx,
            ],
          );
          subId = insSub.rows[0]!.id;
          subsCreated++;
        }

        if (sub.questions.length > 0) {
          // Pull existing question texts under this sub to avoid duplicates.
          const existing = await client.query<{ question: string }>(
            `SELECT question FROM arena_activities WHERE category_id = $1`,
            [subId],
          );
          const existingSet = new Set(existing.rows.map((r) => r.question));

          let qIdx = 0;
          for (const q of sub.questions) {
            const [diff, question, answer, hint, imageUrl] = q;
            if (existingSet.has(question)) {
              qIdx++;
              continue;
            }
            await client.query(
              `INSERT INTO arena_activities
                 (category_id, type, difficulty, question, answer, hint,
                  image_url, is_public, sort_order)
               VALUES ($1, $2, $3, $4, $5, $6, $7, true, $8)`,
              [
                subId,
                imageUrl ? "image" : "text",
                diff,
                question,
                answer,
                hint ?? null,
                imageUrl ?? null,
                qIdx,
              ],
            );
            actsInserted++;
            qIdx++;
          }
        }
        subIdx++;
      }
      sIdx++;
    }

    console.log(
      JSON.stringify(
        { sectionsCreated, subsCreated, actsInserted, totalSections: SECTIONS.length },
        null,
        2,
      ),
    );
  } finally {
    await client.end();
  }
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
