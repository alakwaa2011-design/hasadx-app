/* ─── Main ────────────────────────────────────────────────────────────────── */
async function main() {
  const client = new Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();
  console.log("Connected.");

  try {
    // ── 1. Delete duplicates ────────────────────────────────────────────
    console.log("\n[1/2] Removing duplicate questions...");
    const dedupResult = await client.query(`
      DELETE FROM islamic_questions
      WHERE id NOT IN (
        SELECT MIN(id)
        FROM islamic_questions
        GROUP BY category_id, LOWER(TRIM(question_text))
      )
    `);
    console.log(`  Deleted ${dedupResult.rowCount} duplicate rows.`);

    // ── 2. Insert new unique questions ─────────────────────────────────
    console.log("\n[2/2] Inserting new questions...");
    let totalInserted = 0;

    for (const [categoryName, questions] of Object.entries(NEW_QUESTIONS)) {
      const catRes = await client.query(
        "SELECT id FROM islamic_categories WHERE name = $1 LIMIT 1",
        [categoryName],
      );
      if (catRes.rowCount === 0) {
        console.warn(`  ⚠  Category not found: "${categoryName}" — skipping.`);
        continue;
      }
      const categoryId = catRes.rows[0].id;

      // Fetch existing question texts for this category (lower-trimmed)
      const existRes = await client.query(
        "SELECT LOWER(TRIM(question_text)) AS qt FROM islamic_questions WHERE category_id = $1",
        [categoryId],
      );
      const existingSet = new Set<string>(existRes.rows.map((r: any) => r.qt));

      let inserted = 0;
      for (const [text, a, b, c, d, diff, correctIdx] of questions) {
        if (existingSet.has(text.toLowerCase().trim())) continue;
        const correct = ["A", "B", "C", "D"][correctIdx];
        await client.query(
          `INSERT INTO islamic_questions
             (category_id, question_text, option_a, option_b, option_c, option_d, correct_answer, difficulty)
           VALUES ($1,$2,$3,$4,$5,$6,$7,$8)`,
          [categoryId, text, a, b, c, d, correct, diff],
        );
        inserted++;
        existingSet.add(text.toLowerCase().trim());
      }
      console.log(`  ${categoryName}: +${inserted} new questions.`);
      totalInserted += inserted;
    }

    console.log(`\n✅ Done. Total new questions inserted: ${totalInserted}`);
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
