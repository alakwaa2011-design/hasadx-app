/* =====================================================================
 *  RUNTIME — idempotent insert via raw SQL.
 * ===================================================================== */

async function ensureSection(
  client: Client,
  name: string,
  description: string | undefined,
  order: number,
): Promise<number> {
  const found = await client.query<{ id: number }>(
    "SELECT id FROM islamic_sections WHERE name = $1 AND owner_id IS NULL LIMIT 1",
    [name],
  );
  if (found.rows.length > 0) return found.rows[0].id;
  const inserted = await client.query<{ id: number }>(
    "INSERT INTO islamic_sections (name, description, is_visible, \"order\", owner_id) VALUES ($1, $2, true, $3, NULL) RETURNING id",
    [name, description ?? null, order],
  );
  return inserted.rows[0].id;
}

async function ensureCategory(
  client: Client,
  sectionId: number,
  name: string,
  description: string | undefined,
  level: string,
  order: number,
): Promise<number> {
  const found = await client.query<{ id: number }>(
    "SELECT id FROM islamic_categories WHERE name = $1 AND section_id = $2 AND owner_id IS NULL LIMIT 1",
    [name, sectionId],
  );
  if (found.rows.length > 0) return found.rows[0].id;
  const inserted = await client.query<{ id: number }>(
    "INSERT INTO islamic_categories (section_id, name, description, level, is_visible, \"order\", owner_id) VALUES ($1, $2, $3, $4, true, $5, NULL) RETURNING id",
    [sectionId, name, description ?? null, level, order],
  );
  return inserted.rows[0].id;
}

function validateQuestion(q: Q): string | null {
  const [text, a, b, c, d, , idx] = q;
  if (!text || text.trim().length < 3) return "نص قصير جداً";
  if (text.length > 600) return "نص طويل جداً";
  for (const o of [a, b, c, d]) {
    if (!o || o.trim().length < 1) return "خيار فارغ";
    if (o.length > 250) return "خيار طويل جداً";
  }
  if (![0, 1, 2, 3].includes(idx)) return "correctIndex خارج النطاق";
  // Disallow duplicate options
  const set = new Set([a.trim(), b.trim(), c.trim(), d.trim()]);
  if (set.size !== 4) return "خيارات مكررة";
  return null;
}

async function insertQuestionIfNew(
  client: Client,
  categoryId: number,
  q: Q,
): Promise<"inserted" | "exists" | "invalid"> {
  const err = validateQuestion(q);
  if (err) {
    console.warn(`  ⚠ سؤال غير صالح (${err}): ${q[0].slice(0, 60)}…`);
    return "invalid";
  }
  const [text, a, b, c, d, difficulty, idx] = q;
  const correct = [a, b, c, d][idx];
  const exists = await client.query<{ id: number }>(
    "SELECT id FROM islamic_questions WHERE category_id = $1 AND question_text = $2 LIMIT 1",
    [categoryId, text],
  );
  if (exists.rows.length > 0) return "exists";
  await client.query(
    "INSERT INTO islamic_questions (category_id, question_text, audio_url, option_a, option_b, option_c, option_d, correct_answer, difficulty, created_by) VALUES ($1, $2, NULL, $3, $4, $5, $6, $7, $8, NULL)",
    [categoryId, text, a, b, c, d, correct, difficulty],
  );
  return "inserted";
}

async function getCounts(client: Client): Promise<{ sections: number; categories: number; questions: number }> {
  const r1 = await client.query<{ n: string }>(
    "SELECT COUNT(*)::text AS n FROM islamic_sections WHERE owner_id IS NULL",
  );
  const r2 = await client.query<{ n: string }>(
    "SELECT COUNT(*)::text AS n FROM islamic_categories WHERE owner_id IS NULL",
  );
  const r3 = await client.query<{ n: string }>(
    "SELECT COUNT(*)::text AS n FROM islamic_questions q JOIN islamic_categories c ON c.id = q.category_id WHERE c.owner_id IS NULL",
  );
  return {
    sections: parseInt(r1.rows[0].n, 10),
    categories: parseInt(r2.rows[0].n, 10),
    questions: parseInt(r3.rows[0].n, 10),
  };
}

async function main(): Promise<void> {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is required");
  const client = new Client({ connectionString: url });
  await client.connect();

  console.log("─── توسعة محتوى تحدي حصاد ───");
  const before = await getCounts(client);
  console.log(
    `قبل: ${before.sections} قسم · ${before.categories} فئة · ${before.questions} سؤال`,
  );

  let totalNewSections = 0;
  let totalNewCategories = 0;
  let totalInserted = 0;
  let totalSkipped = 0;
  let totalInvalid = 0;

  // 1. New sections + their categories + questions
  let sectionOrder = 100;
  for (const sec of NEW_SECTIONS) {
    const wasNew = (await client.query("SELECT id FROM islamic_sections WHERE name=$1 AND owner_id IS NULL LIMIT 1", [sec.name])).rows.length === 0;
    const sectionId = await ensureSection(client, sec.name, sec.description, sectionOrder++);
    if (wasNew) totalNewSections++;
    let catOrder = 1;
    for (const cat of sec.categories) {
      const wasNewCat = (await client.query("SELECT id FROM islamic_categories WHERE name=$1 AND section_id=$2 AND owner_id IS NULL LIMIT 1", [cat.name, sectionId])).rows.length === 0;
      const catId = await ensureCategory(client, sectionId, cat.name, cat.description, cat.level ?? "mixed", catOrder++);
      if (wasNewCat) totalNewCategories++;
      for (const q of cat.questions) {
        const r = await insertQuestionIfNew(client, catId, q);
        if (r === "inserted") totalInserted++;
        else if (r === "exists") totalSkipped++;
        else totalInvalid++;
      }
    }
  }

  // 2. New categories under existing sections
  for (const block of NEW_CATEGORIES_IN_EXISTING) {
    const found = await client.query<{ id: number }>(
      "SELECT id FROM islamic_sections WHERE name = $1 AND owner_id IS NULL LIMIT 1",
      [block.sectionName],
    );
    if (found.rows.length === 0) {
      console.warn(`  ⚠ القسم غير موجود، يُتخطى: ${block.sectionName}`);
      continue;
    }
    const sectionId = found.rows[0].id;
    const orderStartRow = await client.query<{ m: number | null }>(
      "SELECT MAX(\"order\") AS m FROM islamic_categories WHERE section_id = $1 AND owner_id IS NULL",
      [sectionId],
    );
    let order = (orderStartRow.rows[0].m ?? 0) + 1;
    for (const cat of block.categories) {
      const wasNewCat = (await client.query("SELECT id FROM islamic_categories WHERE name=$1 AND section_id=$2 AND owner_id IS NULL LIMIT 1", [cat.name, sectionId])).rows.length === 0;
      const catId = await ensureCategory(client, sectionId, cat.name, cat.description, cat.level ?? "mixed", order++);
      if (wasNewCat) totalNewCategories++;
      for (const q of cat.questions) {
        const r = await insertQuestionIfNew(client, catId, q);
        if (r === "inserted") totalInserted++;
        else if (r === "exists") totalSkipped++;
        else totalInvalid++;
      }
    }
  }

  // 3. Top-up existing under-stocked categories — fail loudly if mapping is wrong
  const mappingErrors: string[] = [];
  for (const t of TOPUPS) {
    const sec = await client.query<{ id: number }>(
      "SELECT id FROM islamic_sections WHERE name = $1 AND owner_id IS NULL LIMIT 1",
      [t.sectionName],
    );
    if (sec.rows.length === 0) {
      mappingErrors.push(`القسم غير موجود للتوب-أب: ${t.sectionName}`);
      continue;
    }
    const cat = await client.query<{ id: number }>(
      "SELECT id FROM islamic_categories WHERE name = $1 AND section_id = $2 AND owner_id IS NULL LIMIT 1",
      [t.categoryName, sec.rows[0].id],
    );
    if (cat.rows.length === 0) {
      mappingErrors.push(`الفئة غير موجودة للتوب-أب: ${t.sectionName} / ${t.categoryName}`);
      continue;
    }
    for (const q of t.questions) {
      const r = await insertQuestionIfNew(client, cat.rows[0].id, q);
      if (r === "inserted") totalInserted++;
      else if (r === "exists") totalSkipped++;
      else totalInvalid++;
    }
  }

  const after = await getCounts(client);
  console.log("─── النتائج ───");
  console.log(`أقسام جديدة مُضافة: ${totalNewSections}`);
  console.log(`فئات جديدة مُضافة: ${totalNewCategories}`);
  console.log(`أسئلة جديدة مُدرجة: ${totalInserted}`);
  console.log(`أسئلة موجودة سابقاً (تجاهل): ${totalSkipped}`);
  console.log(`أسئلة غير صالحة (تجاهل): ${totalInvalid}`);
  console.log(
    `بعد: ${after.sections} قسم · ${after.categories} فئة · ${after.questions} سؤال`,
  );

  // Sanity: any category with < 20 questions still
  const lowCats = await client.query<{ section: string; category: string; n: string }>(
    `SELECT s.name AS section, c.name AS category, COUNT(q.id)::text AS n
     FROM islamic_sections s
     JOIN islamic_categories c ON c.section_id = s.id AND c.owner_id IS NULL
     LEFT JOIN islamic_questions q ON q.category_id = c.id
     WHERE s.owner_id IS NULL AND s.name NOT LIKE '%قرآن%' AND c.name NOT LIKE '%قارئ%'
     GROUP BY s.id, s.name, c.id, c.name
     HAVING COUNT(q.id) < 20
     ORDER BY COUNT(q.id) ASC`,
  );
  if (lowCats.rows.length > 0) {
    console.log("─── فئات لا تزال أقل من ٢٠ سؤالاً ───");
    for (const r of lowCats.rows) console.log(`  • ${r.section} / ${r.category}: ${r.n}`);
  } else {
    console.log("✓ جميع الفئات غير القرآنية ≥ 20 سؤالاً.");
  }

  // ─── Hard acceptance-criteria assertions (task #535) ───
  const failures: string[] = [];
  const MIN_SECTIONS = 18;
  const MIN_CATEGORIES = 60;
  const MIN_QUESTIONS = 1500;
  if (after.sections < MIN_SECTIONS)
    failures.push(`عدد الأقسام ${after.sections} < الحد الأدنى ${MIN_SECTIONS}`);
  if (after.categories < MIN_CATEGORIES)
    failures.push(`عدد الفئات ${after.categories} < الحد الأدنى ${MIN_CATEGORIES}`);
  if (after.questions < MIN_QUESTIONS)
    failures.push(`عدد الأسئلة ${after.questions} < الحد الأدنى ${MIN_QUESTIONS}`);
  if (lowCats.rows.length > 0)
    failures.push(`${lowCats.rows.length} فئة غير قرآنية تحت 20 سؤالاً`);
  if (mappingErrors.length > 0)
    failures.push(...mappingErrors.map((e) => `خطأ في تطابق الأسماء: ${e}`));
  if (totalInvalid > 0)
    failures.push(`${totalInvalid} سؤال غير صالح`);

  // Random sample of 20 newly seedable questions
  const sample = await client.query<{ section: string; category: string; question_text: string; correct_answer: string }>(
    `SELECT s.name AS section, c.name AS category, q.question_text, q.correct_answer
     FROM islamic_questions q
     JOIN islamic_categories c ON c.id = q.category_id
     JOIN islamic_sections s ON s.id = c.section_id
     WHERE q.created_by IS NULL
     ORDER BY random() LIMIT 20`,
  );
  console.log("─── عينة عشوائية (٢٠) من الأسئلة المُدرَجة ───");
  for (const r of sample.rows) {
    console.log(`  [${r.section} / ${r.category}] ${r.question_text} → ${r.correct_answer}`);
  }

  await client.end();

  if (failures.length > 0) {
    console.error("─── فشل التحقق من معايير القبول ───");
    for (const f of failures) console.error(`  ✗ ${f}`);
    throw new Error(`Seed validation failed: ${failures.length} issue(s)`);
  }
  console.log("✓ جميع معايير القبول مستوفاة.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
