function validateQuestion(q: Q): string | null {
  const [text, a, b, c, d, , idx] = q;
  if (!text || text.trim().length < 3) return "نص قصير جداً";
  if (text.length > 600) return "نص طويل جداً";
  for (const o of [a, b, c, d]) {
    if (!o || o.trim().length < 1) return "خيار فارغ";
    if (o.length > 250) return "خيار طويل جداً";
  }
  if (![0, 1, 2, 3].includes(idx)) return "correctIndex خارج النطاق";
  const set = new Set([a.trim(), b.trim(), c.trim(), d.trim()]);
  if (set.size !== 4) return "خيارات مكررة";
  if (q[5] !== "hard") return "صعوبة ليست hard";
  return null;
}

async function insertQuestionIfNew(
  client: Client,
  categoryId: number,
  q: Q,
): Promise<"inserted" | "exists" | "invalid"> {
  const err = validateQuestion(q);
  if (err) {
    console.warn(`  ⚠ سؤال غير صالح (${err}): ${q[0].slice(0, 60)}…`);
    return "invalid";
  }
  const [text, a, b, c, d, difficulty, idx] = q;
  const correct = [a, b, c, d][idx];
  const exists = await client.query<{ id: number }>(
    "SELECT id FROM islamic_questions WHERE category_id = $1 AND question_text = $2 LIMIT 1",
    [categoryId, text],
  );
  if (exists.rows.length > 0) return "exists";
  await client.query(
    "INSERT INTO islamic_questions (category_id, question_text, audio_url, option_a, option_b, option_c, option_d, correct_answer, difficulty, created_by) VALUES ($1, $2, NULL, $3, $4, $5, $6, $7, $8, NULL)",
    [categoryId, text, a, b, c, d, correct, difficulty],
  );
  return "inserted";
}

async function main(): Promise<void> {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is required");
  const client = new Client({ connectionString: url });
  await client.connect();

  console.log("─── طبقة الأسئلة الصعبة لتحدي حصاد ───");

  let totalInserted = 0;
  let totalSkipped = 0;
  let totalInvalid = 0;
  const mappingErrors: string[] = [];
  const perCategory: Array<{ section: string; category: string; hardAfter: number }> = [];

  for (const block of HARD_BLOCKS) {
    const sec = await client.query<{ id: number }>(
      "SELECT id FROM islamic_sections WHERE name = $1 AND owner_id IS NULL LIMIT 1",
      [block.sectionName],
    );
    if (sec.rows.length === 0) {
      mappingErrors.push(`القسم غير موجود: ${block.sectionName}`);
      continue;
    }
    const cat = await client.query<{ id: number }>(
      "SELECT id FROM islamic_categories WHERE name = $1 AND section_id = $2 AND owner_id IS NULL LIMIT 1",
      [block.categoryName, sec.rows[0].id],
    );
    if (cat.rows.length === 0) {
      mappingErrors.push(`الفئة غير موجودة: ${block.sectionName} / ${block.categoryName}`);
      continue;
    }
    const categoryId = cat.rows[0].id;
    for (const q of block.questions) {
      const r = await insertQuestionIfNew(client, categoryId, q);
      if (r === "inserted") totalInserted++;
      else if (r === "exists") totalSkipped++;
      else totalInvalid++;
    }
    const after = await client.query<{ n: string }>(
      "SELECT COUNT(*)::text AS n FROM islamic_questions WHERE category_id = $1 AND difficulty = 'hard'",
      [categoryId],
    );
    perCategory.push({
      section: block.sectionName,
      category: block.categoryName,
      hardAfter: parseInt(after.rows[0].n, 10),
    });
  }

  console.log("─── النتائج لكل فئة ───");
  for (const r of perCategory) {
    const ok = r.hardAfter >= 10 ? "✓" : "✗";
    console.log(`  ${ok} ${r.section} / ${r.category}: ${r.hardAfter} سؤال صعب`);
  }
  console.log("─── الإجمالي ───");
  console.log(`أسئلة صعبة جديدة مُدرجة: ${totalInserted}`);
  console.log(`أسئلة صعبة موجودة سابقاً (تجاهل): ${totalSkipped}`);
  console.log(`أسئلة غير صالحة (تجاهل): ${totalInvalid}`);

  // Acceptance criteria assertions (task #536)
  const failures: string[] = [];
  const under = perCategory.filter((r) => r.hardAfter < 10);
  if (under.length > 0)
    failures.push(`${under.length} فئة هدف لا تزال تحت 10 أسئلة صعبة`);
  if (mappingErrors.length > 0)
    failures.push(...mappingErrors.map((e) => `خطأ تطابق: ${e}`));
  if (totalInvalid > 0) failures.push(`${totalInvalid} سؤال غير صالح`);

  await client.end();

  if (failures.length > 0) {
    console.error("─── فشل التحقق من معايير القبول ───");
    for (const f of failures) console.error(`  ✗ ${f}`);
    throw new Error(`Hard-tier seed validation failed: ${failures.length} issue(s)`);
  }
  console.log("✓ كل الفئات المستهدفة لديها ≥ 10 أسئلة صعبة.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
